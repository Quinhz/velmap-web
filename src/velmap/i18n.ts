export function t(key: string, vars: Record<string, any> = {}): string {
    const dict = I18N[S.currentLang] || I18N.en;
    let text = dict[key] !== undefined ? dict[key] : (I18N.en[key] !== undefined ? I18N.en[key] : key);
    for (const [k, v] of Object.entries(vars)) {
        text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
    return text;
}

export function updateLanguageButtons() {
    const enBtn = document.getElementById('lang-btn-en');
    const ptBtn = document.getElementById('lang-btn-pt');
    const activeCls = 'px-2.5 py-1 rounded-md text-[11px] font-medium bg-zinc-100 text-zinc-900 transition-colors';
    const idleCls = 'px-2.5 py-1 rounded-md text-[11px] font-medium text-zinc-400 hover:text-zinc-200 transition-colors';
    if (enBtn) enBtn.className = S.currentLang === 'en' ? activeCls : idleCls;
    if (ptBtn) ptBtn.className = S.currentLang === 'pt-BR' ? activeCls : idleCls;
    const syncToggle = document.getElementById('sync-lang-toggle');
    if (syncToggle) syncToggle.textContent = S.currentLang === 'en' ? 'EN · PT' : 'PT · EN';
}

export function applyTranslations() {
    document.documentElement.lang = S.currentLang === 'pt-BR' ? 'pt-BR' : 'en';
    document.querySelectorAll<HTMLElement>('[data-i18n]').forEach(el => {
        el.textContent = t(el.dataset.i18n || '');
    });
    document.querySelectorAll<HTMLElement>('[data-i18n-html]').forEach(el => {
        el.innerHTML = t(el.dataset.i18nHtml || '');
    });
    document.querySelectorAll<HTMLInputElement>('[data-i18n-placeholder]').forEach(el => {
        el.placeholder = t(el.dataset.i18nPlaceholder || '');
    });
    document.querySelectorAll<HTMLElement>('[data-i18n-title]').forEach(el => {
        el.title = t(el.dataset.i18nTitle || '');
    });
    updateLanguageButtons();
    if (typeof renderBreadcrumbs === 'function') renderBreadcrumbs();
    if (typeof updateSyncStatusUI === 'function') updateSyncStatusUI(S.p2pConnected);
    if (typeof updateDocWordCount === 'function') updateDocWordCount();
    if (typeof S.db !== 'undefined' && S.db) {
        refreshUntouchedStarterCardsLanguage().then(() => {
            fetchAndRenderCards();
            if (typeof renderUnsortedDrawer === 'function') renderUnsortedDrawer();
            if (!document.getElementById('trash-modal')?.classList.contains('hidden')) renderTrashList();
            if (!document.getElementById('settings-modal')?.classList.contains('hidden')) renderSettingsStorage();
            if (S.isHomeViewOpen) renderHomeView();
            if (typeof renderSyncDevicesUI === 'function') renderSyncDevicesUI();
        });
    }
}

export function setLanguage(lang: string) {
    S.currentLang = (lang === 'pt-BR') ? 'pt-BR' : 'en';
    localStorage.setItem(LANG_STORAGE_KEY, S.currentLang);
    applyTranslations();
}

export function toggleLanguage() {
    setLanguage(S.currentLang === 'en' ? 'pt-BR' : 'en');
}
